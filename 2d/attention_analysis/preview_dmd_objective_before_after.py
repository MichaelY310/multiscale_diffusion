"""Read-only requested comparison: original DMD / A5000 / latest student.

Matches rank0's first16 scheduled validation samples (two batches of8).
Existing pixel images are arranged, not retouched or regenerated by an image model.
"""
import argparse
import gc
import json
from pathlib import Path
import sys

import torch
from PIL import Image, ImageDraw, ImageFont
from diffusers import AutoencoderKL

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'DiT'))
from models_multires import DiTMultiRes_models
from dmd_cascade_reuse import CascadeDMD, coupled_noises


@torch.inference_mode()
def main(a):
    run = Path(a.run)
    out = Path(a.output)
    if out.exists():
        raise FileExistsError(out)
    torch.set_num_threads(2)
    torch.cuda.set_device(0)
    torch.cuda.set_per_process_memory_fraction(.08)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    state = torch.load(run / 'checkpoints/latest.pt', mmap=True,
                       map_location='cpu', weights_only=False)
    step = int(state['step'])
    assert state['family'] == 'high_heavy' and state['objective'] == 'dmd_lpips'
    model = DiTMultiRes_models['DiT-L/2'](num_classes=1000, base_size=16)
    model.load_state_dict(state['model'], strict=True)
    del state
    generator = CascadeDMD(model.cuda().eval().requires_grad_(False), 'high_heavy', False)
    rng = torch.Generator(device='cuda').manual_seed(9100000)
    latents, labels = [], []
    with torch.autocast('cuda', dtype=torch.bfloat16):
        for _ in range(2):
            noise, y = coupled_noises(8, torch.device('cuda'), rng)
            pred = generator(noise, y)['cleans'][-1]
            latents.append(pred.cpu().float())
            labels.extend(y.cpu().tolist())
    del generator, model, pred, noise
    gc.collect()
    torch.cuda.empty_cache()
    vae = AutoencoderKL.from_pretrained(a.vae, local_files_only=True).cuda().eval().requires_grad_(False)
    latents = torch.cat(latents)
    out.mkdir(parents=True)
    decoded = []
    for start in range(0, 16, 2):
        result = vae.decode(latents[start:start+2].cuda()/0.18215).sample.float().clamp(-1, 1)
        arrays = ((result+1)*127.5).round().byte().permute(0, 2, 3, 1).cpu().numpy()
        for index, arr in enumerate(arrays, start):
            im = Image.fromarray(arr)
            im.save(out / f'after_{index:03d}_class{labels[index]}.png')
            decoded.append(im)
    font_path = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
    font = ImageFont.truetype(font_path, 17) if Path(font_path).exists() else ImageFont.load_default()
    sheets = []
    for page in range(4):
        sheet = Image.new('RGB', (3*256, 4*284+52), 'white')
        draw = ImageDraw.Draw(sheet)
        titles = ['Original DMD (no reuse)', 'Before: reuse +0', f'After: reuse +{step}']
        for col, title in enumerate(titles):
            draw.text((col*256+5, 5), title, font=font, fill='black')
        draw.text((5, 28), 'Same noise / class; +steps start from A@5000; fixed first16', font=font, fill='black')
        for r in range(4):
            i = page*4+r
            base = run/'preview_0000000'
            images = [Image.open(base/f'teacher_{i:03d}_class{labels[i]}.png').convert('RGB'),
                      Image.open(base/f'student_{i:03d}_class{labels[i]}.png').convert('RGB'), decoded[i]]
            for c, im in enumerate(images):
                assert im.size == (256, 256)
                draw.text((c*256+5, 52+r*284), f'#{i:02d} class {labels[i]}', font=font, fill='black')
                sheet.paste(im, (c*256, 52+r*284+24))
        name = f'before_after_{page+1}.png'
        sheet.save(out/name)
        sheets.append(name)
    metadata = dict(complete=True, checkpoint_step=step, cumulative_updates=5000+step,
                    before='A@5000; already trained for5000 compression updates; NOT zero finetuning',
                    after=f'A@5000 plus {step} DMD+LPIPS updates', sample_count=16,
                    seed=9100000, batch_size=8, labels=labels, sheets=sheets,
                    sampling='3NFE, t999/599/299, noise filling, no extra CFG',
                    reuse='8/24 middle,20/24 fine, high_heavy',
                    peak_gib=torch.cuda.max_memory_allocated()/2**30, NOT_FID=True)
    (out/'manifest.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    print(json.dumps(metadata), flush=True)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--run', required=True)
    p.add_argument('--output', required=True)
    p.add_argument('--vae', required=True)
    main(p.parse_args())
